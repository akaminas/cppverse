// Writes docs/STUDENT_MANUAL_COVERAGE.md from the same data the Sources page
// uses (src/lib/coverage.ts), so the document cannot drift from the site.
//
//   node --experimental-strip-types scripts/generate-coverage.ts           write the file
//   node --experimental-strip-types scripts/generate-coverage.ts --check   fail if it is out of date
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { coverageRows, lessonFactsFrom, type CoverageRow } from '../src/lib/coverage.ts';
import { CITATION, MANUAL } from '../src/data/citation.ts';

const root = join(import.meta.dirname, '..');
const lessonDir = join(root, 'src', 'content', 'lessons');
const out = join(root, 'docs', 'STUDENT_MANUAL_COVERAGE.md');

const files = readdirSync(lessonDir).filter((f) => f.endsWith('.mdx'));
const slugs = new Set(files.map((f) => f.replace(/\.mdx$/, '')));
const facts = Object.fromEntries(files.map((f) => [f.replace(/\.mdx$/, ''), lessonFactsFrom(readFileSync(join(lessonDir, f), 'utf8'))]));
const rows = coverageRows(slugs, facts);

const cell = (s: string | undefined) => (s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
const lessonLinks = (r: CoverageRow) => r.lessons.map((l) => `[${l}](../src/content/lessons/${l}.mdx)`).join(', ');
const nodeList = (r: CoverageRow) => r.nodes.map((n) => `\`${n.id}\``).join(', ');

const count = (pred: (r: CoverageRow) => boolean) => rows.filter(pred).length;
const taught = rows.filter((r) => r.status !== 'excluded');

const lines: string[] = [
  '# Student manual coverage',
  '',
  '<!-- Generated by scripts/generate-coverage.ts. Do not edit by hand. -->',
  '',
  `Source curriculum: *${MANUAL.title}* (${MANUAL.authors.join(", ")}; ${MANUAL.institution}).`,
  '',
  `> ${CITATION}`,
  '',
  'Every section of the manual is listed below. **Instructional** and **advanced** sections are each taught by at least one',
  'atlas concept with a lesson anchor; this is enforced on every build by `scripts/validate-curriculum.ts`. **Excluded**',
  'sections (exercises, solutions, assignments, projects, navigation) are never reproduced; the site offers independently',
  'designed practice and capstones instead. The prose, code and examples on the site are original; the manual is used only',
  'as a map of what must be taught.',
  '',
  '## Summary',
  '',
  '| | Sections |',
  '|---|---:|',
  `| Instructional | ${count((r) => r.section.kind === 'instructional')} |`,
  `| Advanced | ${count((r) => r.section.kind === 'advanced')} |`,
  `| Excluded by policy | ${count((r) => r.status === 'excluded')} |`,
  `| Taught sections fully implemented | ${count((r) => r.status === 'implemented')} of ${taught.length} |`,
  `| Partially implemented | ${count((r) => r.status === 'partial')} |`,
  `| Pending | ${count((r) => r.status === 'pending')} |`,
  '',
  '## Section by section',
  '',
  '| Section | Title | Kind | Atlas concepts | Lessons | Status | Validation | Correction or modernisation notes |',
  '|---|---|---|---|---|---|---|---|',
  ...rows.map((r) =>
    [
      '',
      cell(r.section.section ?? r.section.id),
      cell(r.section.title),
      r.section.kind,
      nodeList(r),
      lessonLinks(r),
      r.status,
      cell(r.validation),
      cell(r.section.kind === 'excluded' ? '' : r.section.notes),
      '',
    ].join(' | ').trim(),
  ),
  '',
  '## What each section is for',
  '',
  ...taught.flatMap((r) => [
    `### ${r.section.section ?? r.section.id} ${r.section.title}`,
    '',
    `- **Concept:** ${cell(r.section.concept)}`,
    `- **Learning objective:** ${cell(r.section.objective)}`,
    `- **Modelling relevance:** ${cell(r.section.modelling)}`,
    '',
  ]),
];
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  if (!existsSync(out)) {
    console.log('coverage document not present (docs/ is not tracked); skipped');
    process.exit(0);
  }
  const current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  if (current !== text) {
    console.error('docs/STUDENT_MANUAL_COVERAGE.md is out of date: run npm run coverage');
    process.exit(1);
  }
  console.log('coverage document is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${rows.length} sections)`);
}
