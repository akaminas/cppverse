import type { DomainId } from './types';

// Model Assembly Views: how a complete computational model is built from
// programming concepts. Each component lists its mathematical definition,
// its role in the algorithm, the lines of the canonical C++ program that
// implement it (1-based, including the header comment), the concepts it
// requires, common mistakes and their consequences.

export interface AssemblyComponent {
  id: string;
  title: string;
  /** Role in the algorithm. */
  role: string;
  /** Mathematical definition (TeX), if the component has one. */
  tex?: string;
  explain: string;
  lines: number[];
  /** Atlas concept ids. */
  prerequisites: string[];
  mistakes: string[];
  consequence: string;
}

export interface Assembly {
  id: string;
  destination: DomainId;
  title: string;
  summary: string;
  file: string;
  components: AssemblyComponent[];
}

